const BY_ID = new Map<number, MoveData>(MOVES.map((m) => [m.id, m]));

export function getMove(id: number): MoveData | undefined {
  return BY_ID.get(id);
}

export function moveName(id: number): string {
  if (id === 0) return '-';
  return BY_ID.get(id)?.name ?? `UNKNOWN_MOVE_${id}`;
}

export function moveTypeId(id: number): number {
  const move = BY_ID.get(id);
  return move ? TYPE_IDS[move.type] : TYPE_IDS.NORMAL;
}
