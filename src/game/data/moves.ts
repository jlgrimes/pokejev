import { TYPE_IDS, type TypeName } from './types.ts';

export interface MoveData {
  id: number;
  name: string;
  type: TypeName;
  /** Base power. 0 means status move; see `special` for fixed-damage/OHKO moves. */
  power: number;
  /** Accuracy out of 100. `null` means it never misses (Swift) or is self-targeting. */
  accuracy: number | null;
  pp: number;
  /** Non-standard damage behaviour Jev needs to know about. */
  special?: 'ohko' | 'fixed' | 'variable' | 'multi-hit' | 'two-turn' | 'recharge' | 'recoil' | 'drain' | 'heal';
  note?: string;
}

